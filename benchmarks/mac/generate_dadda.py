"""Emit reproducible structural Dadda two-row reducers."""
from pathlib import Path


def reducer(booth):
    name = "booth" if booth else "unsigned"
    lines = [f"module mac_dadda_{name} (input wire [23:0] a, b,",
             "    output wire [47:0] row_a, row_b);"]
    columns = [[] for _ in range(48)]
    if booth:
        corrections = 0
        lines.append("    wire [26:0] padded = {2'b00, b, 1'b0};")
        for i in range(13):
            lines += [f"    wire [25:0] pp{i};",
                      f"    mac_booth4_row digit_{i}(a, padded[{2*i} +: 3], pp{i});"]
            for bit in range(min(26, 48 - 2*i)):
                token = f"pp{i}[{bit}]"
                if bit == 25:
                    token = "~" + token
                    corrections -= 1 << (2*i + 25)
                columns[2*i + bit].append(token)
        for bit in range(48):
            if (corrections >> bit) & 1:
                columns[bit].append("1'b1")
    else:
        for i in range(24):
            lines.append(f"    wire [23:0] pp{i} = a & {{24{{b[{i}]}}}};")
            for bit in range(24):
                columns[i + bit].append(f"pp{i}[{bit}]")
    heights = [2]
    while heights[-1] < max(map(len, columns)):
        heights.append(3 * heights[-1] // 2)
    compressor = 0
    for target in reversed(heights[:-1]):
        lines.append(f"    // Reduce to Dadda height {target}.")
        for bit, column in enumerate(columns):
            while len(column) > target:
                take = 3 if len(column) >= target + 2 else 2
                x, y, z = [column.pop(0) for _ in range(take)] + ["1'b0"] * (3-take)
                t, c = f"sum_{compressor}", f"carry_{compressor}"
                compressor += 1
                lines.append(f"    wire {t} = {x} ^ {y} ^ {z};")
                column.append(t)
                if bit < 47:
                    lines.append(f"    wire {c} = ({x} & {y}) | ({x} & {z}) | ({y} & {z});")
                    columns[bit + 1].append(c)
    for bit, column in enumerate(columns):
        x, y = (column + ["1'b0", "1'b0"])[:2]
        lines += [f"    assign row_a[{bit}] = {x};", f"    assign row_b[{bit}] = {y};"]
    return "\n".join([*lines, "endmodule"])


if __name__ == "__main__":
    Path(__file__).with_name("dadda_generated.sv").write_text(
        "`timescale 1ns/1ps\n// Generated by generate_dadda.py.\n" +
        "\n\n".join(reducer(booth) for booth in (False, True)) + "\n")
